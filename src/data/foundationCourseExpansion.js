function diagram(title, type, nodes) {
  return `
    <figure class="concept-diagram ${type}">
      <figcaption>${title}</figcaption>
      <div class="diagram-track">
        ${nodes.map(([name, detail, extra], index) => `
          <div class="diagram-node">
            <span class="diagram-index">${String(index + 1).padStart(2, '0')}</span>
            <strong>${name}</strong>
            <small>${detail}</small>
            ${extra ? `<em>${extra}</em>` : ''}
          </div>
        `).join('')}
      </div>
    </figure>
  `
}

function q(id, topic, question, choices, answer, explanation) {
  const number = Number(id.split('-').at(-1))
  const level = number <= 8 ? 'beginner' : number <= 14 ? 'intermediate' : 'advanced'
  return { id, topic, level, question, choices, answer, explanation }
}
